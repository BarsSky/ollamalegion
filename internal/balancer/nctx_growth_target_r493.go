package balancer

import (
	"ollama-loadbalancer/internal/cppbackend"
)

// nctxGrowthStepR493 — ступень роста окна. 8192 = типовой шаг промпта агентского
// хода (столько прибавляет история за один ход); меньше делать бессмысленно —
// вернётся «+5k на каждый ход», больше — лишний KV-cache.
const nctxGrowthStepR493 = 8192

// growthTargetR493 — до какого окна (НА КЛИЕНТА) расти и нужно ли расти вообще.
//
// needed — сколько нужно запросу, loaded — окно слота сейчас (0 = неизвестно),
// ceiling — потолок окна на клиента (0 = неизвестен).
//
// Возвращает (target, true) только когда рост действительно что-то меняет.
func growthTargetR493(needed, loaded, ceiling int) (int, bool) {
	if needed <= 0 {
		return 0, false
	}
	aligned := cppbackend.PadContext(needed)
	if aligned <= 0 {
		return 0, false
	}
	// Запросу нужно БОЛЬШЕ физического/операторского потолка — рост бессмыслен:
	// перезагрузка на потолок всё равно не обслужит этот запрос, а стоит она
	// выгрузки 27B. Прежнее правило (до R493) отказывало ровно так же — здесь оно
	// сохранено и проверяется по «нужному», а не по урезанной цели.
	if ceiling > 0 && needed > ceiling {
		return 0, false
	}
	// Уже покрыто (после выравнивания) — рост не нужен. Это и есть защита от
	// перезагрузки ВНИЗ: 149809 выравнивается в 150016 и совпадает с
	// загруженным, а не «меньше на 207».
	if loaded > 0 && aligned <= loaded {
		return 0, false
	}
	// Цель кратна ступени: подъём «до нужного + 200 токенов» гарантирует, что
	// следующий ход агента снова упрётся в окно и потребует ещё одной выгрузки
	// 27B — именно это и видно в архиве цепочкой 131072→137216→143872→150016.
	target := roundUpR493(aligned, nctxGrowthStepR493)
	if ceiling > 0 && target > ceiling {
		// Потолок — это предел, который нельзя превысить даже на 255 токенов
		// выравнивания: воркер выровняет присланное вверх (GGML_PAD), и окно
		// вышло бы за объявленный оператором/моделью предел. Поэтому вниз до
		// кратного 256, а не «как есть».
		target = floorAlignR493(ceiling, cppbackend.ContextPadStep)
	}
	if loaded > 0 && target <= loaded {
		return 0, false
	}
	return target, true
}

// roundUpR493 — вверх до кратного step.
func roundUpR493(v, step int) int {
	if step <= 0 || v <= 0 {
		return v
	}
	if rem := v % step; rem != 0 {
		v += step - rem
	}
	return v
}

// floorAlignR493 — вниз до кратного step (для потолков, которые нельзя превышать).
func floorAlignR493(v, step int) int {
	if step <= 0 || v <= 0 {
		return v
	}
	return (v / step) * step
}
