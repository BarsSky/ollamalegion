package balancer

// layout_skip_offline_r315.go — R315 (2026-10-30): недоступному бэкенду приказ о
// раскладке не отправляется.
//
// ЖИВОЙ ФАКТ. Донор выключен, запись бэкенда это знает (`ollama_unavailable`), а
// гард раскладки каждые 5 минут пытался отправить ему PUT и ждал сетевой
// таймаут: «EnsureRPCLayout: не удалось применить раскладку» — строка, которая
// ничего не сообщает оператору (он и так видит узел мёртвым) и повторяется до
// бесконечности. Ограничитель R299 сузил частоту, но не убрал бессмысленное
// сетевое ожидание и не сказал «почему не пробуем».
//
// ЧТО ЗДЕСЬ: один вопрос — «есть ли смысл слать приказ этому бэкенду». Ответ
// «нет» только для САМОГО адресата, когда его статус достоверно говорит «не в
// сети». Главного это не касается никогда: даже со всеми мёртвыми донорами он
// обязан получить приказ «раскладка выключена», иначе продолжит грузить модель с
// мёртвым списком узлов (класс R118.2, живая авария).

import (
	"time"

	"ollama-loadbalancer/pkg/types"
)

// layoutSkipLogR315 — ограничитель: «приказ не отправляется» не чаще раза в час
// на пару (бэкенд, статус). Смена статуса меняет ключ, поэтому возвращение узла
// и повторное падение видны в логе сразу.
var layoutSkipLogR315 = newLogRateLimiter(time.Hour)

// layoutPushHopelessR315 — приказ этому бэкенду заведомо не дойдёт.
//
// Список статусов намеренно узкий: только те, что означают «узел не в сети»
// однозначно. `unhealthy` и `degraded` сюда НЕ входят: узел может отвечать по
// одному порту и молчать по другому, и решение о раскладке принимает TCP-проба
// ниже, а не статус пула.
func (p *Proxy) layoutPushHopelessR315(b *types.Backend) bool {
	if p == nil || b == nil {
		return false
	}
	switch b.Status {
	case types.StatusOffline, types.StatusOllamaUnavailable:
		return true
	}
	return false
}