//     обратная совместимость для профилей и старых вызовов;
//  3. пустой/пробельный фильтр трактуется как «без фильтра».
package api

import "testing"

func TestR228_BackendFilterScopesApply(t *testing.T) {
	if !matchesBackendFilter("gpu-1", "gpu-1") {
		t.Error("выбранный бэкенд должен попадать в фильтр")
	}
	if matchesBackendFilter("donor-9", "gpu-1") {
		t.Error("чужой бэкенд (донор) не должен применяться — именно это ломалось живьём")
	}
	// Обратная совместимость: без параметра применяем ко всем.
	if !matchesBackendFilter("gpu-1", "") {
		t.Error("без фильтра бэкенд должен применяться")
	}
	if !matchesBackendFilter("gpu-1", "   ") {
		t.Error("пробельный фильтр должен означать «без фильтра»")
	}
	// Точное совпадение, а не префикс/подстрока: иначе gpu-1 задел бы gpu-10.
	if matchesBackendFilter("gpu-10", "gpu-1") {
		t.Error("фильтр должен сравниваться точно, а не по префиксу")
	}
}
