// WindowFeasibility проверяет, помещается ли запрошенное окно в потолок бэкенда.
//
// Возвращает:
//   - (true, ceiling, "")  — окно допустимо (или потолок неизвестен: запрещать
//     по догадке нельзя — «неизвестно» не значит «нельзя»);
//   - (false, ceiling, why) — заведомо не помещается, ceiling > 0.
//
// requested <= 0 означает «окно не задано» → проверять нечего.
func (p *Proxy) WindowFeasibility(backendID, modelName string, requested int) (bool, int, string) {
	if p == nil || requested <= 0 {
		return true, 0, ""
	}
	if !p.BackendExists(backendID) {
		// Бэкенда нет — судить о его потолке нельзя, отказ был бы догадкой.
		return true, 0, ""
	}

	// Наименьший из ИЗВЕСТНЫХ потолков (0 = «неизвестно», не участвует).
	ceiling := 0
	for _, v := range []int{
		p.getGGUFMaxContext(backendID),   // физика модели
		p.declaredWindowTotal(modelName), // заявленное оператором окно
		p.profileCapCtx(modelName, true), // «больше нельзя» из профиля
	} {
		if v > 0 && (ceiling == 0 || v < ceiling) {
			ceiling = v
		}
	}
	if ceiling <= 0 {
		return true, 0, ""
	}
	if requested > ceiling {
		return false, ceiling, "requested context window exceeds model/backend ceiling"
	}
	return true, ceiling, ""
}
