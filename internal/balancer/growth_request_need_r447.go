// growth_request_need_r447.go — R447 (2026-11-06): «окну мало» и «окно нужно
// растить» — два разных вопроса, и до этой правки второй решался без первого.
//
// ЖИВОЙ ДЕФЕКТ (и он же причина красного CI). Запрос «Привет!» на модель,
// загруженную с окном 2048, получал отказ и ЗАПУСКАЛ перезагрузку модели, хотя
// промпту нужно 3 токена:
//
//	model "test-model" needs 4099 tokens of context; the loaded window is 2048 —
//	the balancer has started reloading the model to the requested window, retry in 60s
//
// Откуда 4099: `neededWindowTokensR330` = оценка промпта + БЮДЖЕТ ВЫВОДА (4096).
// Бюджет вывода входит в «сколько нужно окну», но НЕ означает, что модель не
// может ответить: воркер урезает num_predict по свободному месту сам. Рост нужен
// только когда места под ответ реально не остаётся (см. ниже), а не всегда,
// когда `needed` больше окна.
//
// Последствия прежнего правила:
//
//   - балансер рвал работающий процесс перезагрузкой модели (unload+load) на
//     каждый короткий запрос — то самое «медленно и отваливается» на стенде;
//   - стриминговый путь (R301) отказывал в обслуживании промпта, который воркер
//     обслужил бы укороченным ответом;
//   - исход зависел от свободной VRAM (рост разрешён, только пока физика это
//     позволяет), поэтому один и тот же вход давал то 200 (0.01 c), то 503 +
//     перезагрузку (0.5 c) — флак `TestChatStreaming` в CI.

package balancer

import "fmt"

// growthNeedR447 — нужен ли запросу рост окна.
//
// Растим окно только тогда, когда этого требует САМ ЗАПРОС:
//
//  1. промпт не влезает в окно одного слота — иначе воркер ответит кадром
//     ошибки внутри 200 (живой дефект R301);
//  2. клиент ЯВНО попросил окно больше загруженного (R385: «просил 16384 при
//     загруженных 8192» — законное требование, а не догадка балансера);
//  3. после префилла не остаётся места под осмысленный ответ, то есть
//     `loaded - estimated < agentOutputReserveMinTokens` (256). Это нижняя
//     граница «ход агента вообще имеет смысл» из R253: сюда попадает окно
//     2048 при промпте 2000, и туда НЕ попадает окно 2048 при промпте в
//     3 токена (свободно ≈2045).
//
// Полный бюджет вывода (`agentOutputBudget`, 4096 по умолчанию) в условие
// намеренно НЕ входит: это верхняя граница запроса, а не требование модели —
// именно её сравнение с окном и давало 503 на короткий вопрос.
//
// estimated <= 0 означает «оценки промпта нет»: сравнивать нечего, полагаемся
// только на явно запрошенное окно.
func growthNeedR447(estimated, loaded, requested int) (need bool, why string) {
	if loaded <= 0 {
		// Загруженное окно неизвестно — спекулировать нечем, решение принимает
		// прежний путь (R299/R301 по своим правилам).
		return false, "загруженное окно неизвестно"
	}
	if estimated > 0 {
		if estimated > loaded {
			return true, fmt.Sprintf("промпт (%d) не влезает в окно слота (%d)", estimated, loaded)
		}
		if room := loaded - estimated; room < agentOutputReserveMinTokens {
			return true, fmt.Sprintf("под ответ остаётся %d токенов (промпт %d, окно %d), меньше минимума %d",
				room, estimated, loaded, agentOutputReserveMinTokens)
		}
	}
	if requested > loaded {
		return true, fmt.Sprintf("клиент попросил окно %d больше загруженного %d", requested, loaded)
	}
	return false, fmt.Sprintf("промпт (%d) влезает в окно слота (%d) с местом под ответ, клиент больше не просил",
		estimated, loaded)
}
