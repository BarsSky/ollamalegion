// load_without_unready_node_r380.go — R380 (2026-11-01): непринятый узел
// раскладки НЕ передаётся в мост на этой загрузке.
//
// ЗАЧЕМ. R177 добавил гейт перед загрузкой: реальная команда протокола
// (запрос памяти устройства) несколько раз, и по её результату мост говорит,
// свободен ли узел. Но результат гейта НЕ влиял на список серверов: строка
// `applyRPCServersR105(&cfg, loadRPCServers)` отправляла адреса в мост при
// любом исходе. В логах это выглядит безобидно («узел не принял — грузим на
// локальные»), а на деле llama.cpp всё равно пытался поднять RPC-транспорт к
// занятому узлу.
//
// ЖИВОЙ ДЕФЕКТ (стенд, 2026-11-01). Слот донорского rpc-server занят чужим
// соединением (узел обслуживает одно за раз). Загрузка при этом:
//
//	negotiate_hello: RPC server did not answer the hello handshake
//	get_dispatcher: RPC node unavailable, skipping: RPC handshake failed for 100.64.0.7:50052
//	[bridge] RPC: узел 100.64.0.7:50052 НЕ подключён
//	SIGSEGV: segmentation violation
//	signal arrived during cgo execution
//
// То есть процесс воркера падал (и перезапускался), вместо того чтобы просто
// загрузить модель на локальную карту и честно пометить layout_degraded.
// Повторить SIGSEGV удалось не в каждом прогоне (гонка в инициализации RPC:
// иногда успевало отказать чисто) — поэтому чинится не «место падения», а
// опасный путь: если гейт сказал «узел не принял команду», адрес узла в мост
// на этой загрузке не уходит ВООБЩЕ.
package cppbackend

// bridgeServersForLoadR380 — список RPC-серверов, который допустимо отдать
// мосту на одну конкретную загрузку.
//
// ready=true  — гейт подтвердил, что узел обслуживает команды: отдаём как есть.
// ready=false — узел занят/не ответил: НЕ отдаём ни одного адреса (загрузка
// пойдёт на локальные устройства, а раскладка честно пометится degraded).
func bridgeServersForLoadR380(servers []string, ready bool) []string {
	if !ready || len(servers) == 0 {
		return nil
	}
	return servers
}
