//
//	`defaultIfZero` существовал в ДВУХ вариантах с РАЗНОЙ семантикой:
//	  - cmd/balancer: `v == 0 → def` (ноль и только ноль);
//	  - internal/balancer: `v <= 0 → def` (ноль И отрицательные).
//	Свести их в одну функцию значило бы изменить поведение одного из пакетов, а
//	рефакторинг (шаг R7, §3 плана) поведение не меняет. Поэтому здесь ОБЕ
//	семантики, но с именами, которые говорят, что именно происходит: разница
//	перестала быть скрытой в двух копиях с одинаковым именем.
//
//	`minInt`/`maxInt` (по две копии в трёх пакетах) сюда НЕ перенесены: в Go 1.21
//	есть встроенные `min`/`max` для упорядочиваемых типов, и лучший вариант —
//	удалить копии, а не завести третью. Это и сделано в шаге R7.
//
//	`roundUpPow2` в плане назван дублем, но по факту это ОДНА реализация
//	(internal/balancer/nctx_reload.go) плюс тонкая обёртка `RoundUpPow2` для
//	внешних вызовов. Причём она НЕ «просто вверх до степени двойки»: у неё есть
//	пол 512 токенов. Переносить её в общий пакет под нейтральным именем опасно:
//	следующий читатель решит, что это чистая математика без пола, и сломает
//	перезагрузку окна. Поэтому реализация осталась на месте, с комментарием в
//	месте определения.
package numutil

// DefaultIfZeroInt — `0 → def` (и только ноль: отрицательное значение
// сохраняется). Семантика cmd/balancer.
func DefaultIfZeroInt(v, def int) int {
	if v == 0 {
		return def
	}
	return v
}

// DefaultIfNotPositiveFloat — `<= 0 → def` (ноль И отрицательные). Семантика
// internal/balancer (score/веса: отрицательный вес — мусор, берём дефолт).
func DefaultIfNotPositiveFloat(v, def float64) float64 {
	if v <= 0 {
		return def
	}
	return v
}
