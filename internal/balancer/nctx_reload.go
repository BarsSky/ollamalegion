// roundUpPow2 ? ?????????? ????? ?? ????????? ??????? 2.
// ??????? 512 (?????? llama.cpp ?? ?????????).
func roundUpPow2(v int) int {
	if v <= 0 {
		return 512
	}
	if v < 512 {
		return 512
	}
	p := 1
	for p < v {
		p <<= 1
	}
	return p
}

