// context_budget.go — R502 (2026-11-19), аудит S4 (N-9): ОДИН бюджет ответа на
// оба конца.
//
// ЖИВОЙ ДЕФЕКТ. «Влезает ли промпт» решали два разных числа:
//
//   - балансер (`internal/balancer/growth_request_need.go`) считал, что под
//     ответ достаточно места `256` токенов; если меньше — растим окно;
//   - воркер (`cmd/cppworker/inference.go`) требует жёсткие `512`
//     (`minNPredictClamp`): при `promptTokens + 512 + 1 > n_ctx` он отвечает
//     HTTP 413 `PromptExceedsNCtxError`.
//
// Для остатка 300…511 балансер решал «обслужить» (очередь и окно не трогаются), а
// воркер отказывал — клиент получал 413 при живом запасе окна, и снаружи это
// выглядело как «балансер неверно считает окно».
//
// ПОЧЕМУ 512, А НЕ 256. 512 — жёсткое требование воркера: ниже него он не
// опускает n_predict. Балансер обязан считать по СТРОЖАЙШЕМУ из двух, иначе
// обещает то, что второй конец отвергнет.
//
// Почему константа в `pkg/types`: это общий пакет балансера и воркера (воркер уже
// импортирует его для контрактов), а `pkg/protocol` воркер не импортирует.
package types

// ContextBudgetMinAnswerTokensR502 — минимальный бюджет ОТВЕТА в токенах, ниже
// которого промпт считается не влезающим в окно слота.
//
// Одна величина на балансер (решение о росте окна) и воркер (кламп n_predict):
// два разных числа давали балансеру право обещать то, что воркер отвергает
// (аудит N-9).
const ContextBudgetMinAnswerTokensR502 = 512
