// растить» — два разных вопроса, и до этой правки второй решался без первого.
//
// ЖИВОЙ ДЕФЕКТ (и он же причина красного CI). Запрос Cline/теста «привет» на
// модель, загруженную с окном 2048, получал отказ и ЗАПУСКАЛ перезагрузку
// модели, хотя промпту нужно 3 токена:
//
//	model "test-model" needs 4099 tokens of context; the loaded window is 2048 —
//	the balancer has started reloading the model to the requested window, retry in 60s
//
// Откуда 4099: `neededWindowTokensR330` = оценка промпта + БЮДЖЕТ ВЫВОДА (4096).
// Бюджет вывода входит в «сколько нужно окну», но не в «влезает ли промпт», а
// воркер урезает num_predict по свободному месту сам. В результате:
//
//   - решение о росте принималось по числу, которого моделью ещё не требуется;
//   - стриминговый путь (R301) отказывал в обслуживании промпта, который воркер
//     обслужил бы укороченным ответом;
//   - балансер рвал работающий процесс перезагрузкой модели на каждый короткий
//     запрос — то самое «медленно и отваливается» на стенде.
//
// Плюс это был ИСТОЧНИК ФЛАКА: рост разрешён только пока физика (свободная
// VRAM/RAM) это позволяет, а она на живой машине меняется. Один и тот же
// короткий запрос то получал 200, то 503+перезагрузку (0.5 c вместо 0.01 c).
// Решение не должно зависеть от свободной памяти, если окно и не нужно расти.

package balancer

import "fmt"

// growthNeedR447 — нужен ли запросу рост окна.
//
// Растим окно только тогда, когда этого требует САМ ЗАПРОС:
//
//   - промпт не влезает в окно одного слота (иначе воркер ответит кадром ошибки
//     внутри 200 — живой дефект R301);
//   - клиент ЯВНО попросил окно больше загруженного (R385: «просил 16384 при
//     загруженных 8192» — это законное требование, а не догадка балансера).
//
// Во всех остальных случаях загруженного окна хватает: запрос обслуживается
// как есть, без перезагрузки модели и без отказа. Бюджет вывода сюда намеренно
// не входит — его урезает воркер, а не балансер (см. шапку файла).
//
// estimated <= 0 означает «оценки промпта нет»: сравнивать нечего, полагаемся
// только на явно запрошенное окно.
func growthNeedR447(estimated, loaded, requested int) (need bool, why string) {
	if loaded <= 0 {
		// Загруженное окно неизвестно — спекулировать нечем, решение принимает
		// прежний путь (R299/R301 по своим правилам).
		return false, "загруженное окно неизвестно"
	}
	promptFits := estimated <= 0 || estimated <= loaded
	if !promptFits {
		return true, fmt.Sprintf("промпт (%d) не влезает в окно слота (%d)", estimated, loaded)
	}
	if requested > loaded {
		return true, fmt.Sprintf("клиент попросил окно %d больше загруженного %d", requested, loaded)
	}
	return false, fmt.Sprintf("промпт (%d) влезает в окно слота (%d), клиент больше не просил", estimated, loaded)
}
