// handlers_chat_retry_r188.go — R188 (2026-10-20): повтор генерации ограничен,
// если клиент сам задал длину ответа.
//
// ЖИВОЙ РАЗБОР (Cline через Ollama API, Qwen3.8-27B). Клиент получал минуты
// тишины и обрывался на середине хода. В воркере на tools-пути
// (writeChatStreamResponseWithTools) при пустом/неразобранном выводе выполняется
// ПОВТОР ВСЕЙ генерации: outputBuf.Reset() + generateStreamWithRamFallback. На
// 27B-модели с CPU-оффлоадом один проход — 2-6 минут, то есть цикл повторов
// растягивал «ход» на десятки минут, держал слот и выглядел в клиенте как
// зависание.
//
// Ключевой факт: если клиент ОГРАНИЧИЛ длину ответа (options.num_predict /
// max_tokens), обрезанный ход — ожидаемый результат ЭТОГО ограничения, а не
// сбой модели. Повторять его бессмысленно: тот же лимит отрежет тот же вывод.
// Поэтому при клиентском лимите разрешён максимум ОДИН повтор (две генерации),
// а не полный бюджет повторов.
package main

// emptyOutputRetryBudget — сколько повторов генерации допускается.
//
// clientCapped = клиент задал положительный num_predict/max_tokens.
func emptyOutputRetryBudget(clientCapped bool) int {
	if clientCapped {
		return 1
	}
	return maxEmptyOutputRetries
}
