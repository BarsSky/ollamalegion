// prefix_cache.h — R493 (2026-11-16): переиспользование KV-кэша префилла.
//
// ЗАЧЕМ. Мост держит llama_context между запросами, но перед каждым запросом
// делает reset_inference_state() — то есть KV-кэш очищается, и следующий ход
// агента заново считает ВЕСЬ промпт. На втором стенде это измерено:
// 94 хода Cline на Qwen3.8-27B, медиана 213 с на ход при медиане 260
// сгенерированных токенов; декод там же 23-33 ток/с, значит ~200 с из хода —
// повторный префилл 80-90 тыс. токенов (см.
// docs/plans/2026-11-16-second-stand-qwen38-speed.md).
//
// РЕШЕНИЕ. Кэшируем токены последнего запроса (промпт + сгенерированное) и на
// следующем запросе находим самый длинный общий префикс: KV-кэш обрезается до
// него (llama_memory_seq_rm), а в llama_decode уходит только хвост. Агентский
// цикл (Cline и подобные) дописывает историю в конец, поэтому общий префикс —
// это почти весь предыдущий промпт.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. Здесь только ЧИСТАЯ логика (сравнение префиксов и
// чтение выключателя) без единого включения llama.cpp. Её можно собрать и
// прогнать тестом на любой машине, без GPU и без модели
// (c/bridge/tests/test_prefix_cache.c). Само переиспользование KV живёт в
// bridge.c, потому что требует llama_memory_seq_rm.
//
// ВЫКЛЮЧАТЕЛЬ. CPPWORKER_PREFIX_CACHE=0/false/no/off выключает
// переиспользование (каждый запрос снова считает весь промпт). По умолчанию —
// включено.
#ifndef BRIDGE_PREFIX_CACHE_H
#define BRIDGE_PREFIX_CACHE_H

#include <stdint.h>

// bridge_prefix_common_len — длина общего префикса двух последовательностей
// токенов. Возвращает 0 при NULL/неположительных длинах.
int bridge_prefix_common_len(const int32_t* a, int na, const int32_t* b, int nb);

// bridge_prefix_cache_enabled — включено ли переиспользование (env-выключатель).
int bridge_prefix_cache_enabled(void);

// bridge_prefix_cache_min_reuse — минимальный общий префикс, ради которого
// вообще стоит обрезать KV: на нескольких токенах экономия меньше стоимости
// вызова llama_memory_seq_rm и похода в кэш.
int bridge_prefix_cache_min_reuse(void);

#endif // BRIDGE_PREFIX_CACHE_H
