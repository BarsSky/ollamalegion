package balancer

// tool_args_fragment_r254.go — R254 (2026-10-28): НЕ ремонтировать незакрытый
// фрагмент аргументов инструмента.
//
// ЖИВОЙ ДЕФЕКТ (Cline, длинная серия tool-call'ов). На /v1 каждый SSE-чанк с
// tool_call нормализуется отдельно, и на НЕПОЛНОМ фрагменте arguments
// repairToolArguments уходил в ветку «это не JSON» — там при схеме с ОДНИМ
// обязательным полем обрывок оборачивался в {"field":"<обрывок>"} и уезжал
// клиенту. Cline склеивает дельты по index, поэтому обёртка склеивалась с
// последующими кусками настоящего JSON → битые аргументы → «✖ Invalid input» →
// повтор того же вызова до остановки задачи.
//
// ПРАВИЛО. Ремонт аргументов — только для ПОЛНОГО значения: успешный
// json.Unmarshal (объект/строка/массив — любая законченная JSON-форма). Дельта
// стрима, которая ещё не закрыта, отдаётся клиенту КАК ЕСТЬ (форма id/type/index
// нормализуется отдельно — это не аргументы). Без-JSON «голая команда» тоже
// ремонтируется, но только когда значение пришло ЦЕЛИКОМ (non-stream ответ),
// а не дельтой: иначе от «голой команды» не отличить обрывок.

import (
	"encoding/json"
	"strings"
	"sync"

	"ollama-loadbalancer/pkg/logger"
)

// repairableToolArgsFragment — можно ли применять ремонт к этой строке аргументов.
//
// complete == true означает «значение пришло целиком» (non-stream ответ или
// собранный финальный ответ): тогда допустим и ремонт не-JSON «голой команды»
// (R186). В стриме (complete == false) ремонт — только для законченного JSON.
//
// ПОЧЕМУ ТАК. У незакрытого фрагмента нет способа отличить «модель пишет JSON» от
// «модель написала голую команду»: обе строки не разбираются. Ремонт в этом
// состоянии меняет смысл данных (обёртка единственного обязательного поля), и
// клиент получает испорченные аргументы.
func repairableToolArgsFragment(args string, complete bool) bool {
	trimmed := strings.TrimSpace(args)
	if trimmed == "" {
		return false
	}
	// Полный JSON любой формы: объект, строка, число, массив, null.
	if json.Valid([]byte(trimmed)) {
		return true
	}
	// Не JSON. Различаем два случая:
	//   - текст НАЧИНАЕТСЯ как JSON ({, [ или ") — это ОБРЫВОК значения, и он
	//     недопустим к ремонту даже в финальном чанке: обёртка обрывка в
	//     обязательное поле — ровно тот дефект, который лечится в R254;
	//   - текст не похож на JSON вовсе (голая команда вроде `hel`) — ремонт
	//     допустим, но только когда значение пришло ЦЕЛИКОМ (R186).
	// В стриме «голая команда» неотличима от обрывка, поэтому там запрещено всё.
	if !complete {
		return false
	}
	return !looksLikeJSONFragmentStart(trimmed)
}

// looksLikeJSONFragmentStart — текст начинается как JSON-значение (значит, если он
// не разбирается, это обрывок, а не «голая команда»).
func looksLikeJSONFragmentStart(s string) bool {
	if s == "" {
		return false
	}
	switch s[0] {
	case '{', '[', '"':
		return true
	}
	return false
}

// toolRepairState — состояние ремонта аргументов на ОДИН стрим.
//
// ЗАЧЕМ. Диагностика «ремонт пропущен, потому что фрагмент не закрыт» должна
// попасть в лог один раз: иначе на длинном tool-call'е она печатается на каждый
// чанк и топит журнал (сотни строк на один вызов).
type toolRepairState struct {
	once sync.Once
	// logged — сколько раз диагностика реально записана (для тестов: ровно 1).
	logged int
}

// noteSkipped — записать в debug ОДИН раз на стрим, почему ремонт не применён.
func (s *toolRepairState) noteSkipped(tool, reason string) {
	if s == nil {
		return
	}
	s.once.Do(func() {
		s.logged++
		if logger.Get() == nil {
			return
		}
		logger.Get().Debugw("tool args repair skipped (fragment not complete)",
			"tool", tool, "reason", reason)
	})
}
