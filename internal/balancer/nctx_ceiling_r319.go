package balancer

import "strconv"

// nctx_ceiling_r319.go — R319 (2026-10-30): КЛАСТЕРНЫЙ потолок авто-роста окна
// как отдельное, всегда доступное значение.
//
// ЖИВАЯ ЖАЛОБА, ради которой это здесь. Оператор много раз спрашивал одно и то
// же: «модель обучена на 131072, VRAM даёт 131072 — почему фактическое окно
// 32768?». Ответ лежит в трёх разных числах:
//
//	gguf_max_context (обучение)      — жёсткий верх модели;
//	max_vram_n_ctx / feasible        — что влезает в VRAM;
//	AutoReloadMaxNCtx (LB_NCTX_RELOAD_MAX_N_CTX) — потолок АВТО-роста от операции.
//
// Первые два доезжают до карточки (R83: feasibleMaxContext/ggufMaxContext).
// Третье НЕ ВИДНО НИГДЕ: /api/v1/cluster/config его не отдаёт (там есть только
// llamaCpp.contextLength — совсем другое поле), в реестр настроек он не внесён,
// а в /api/v1/cppworker/model-profiles он был доступен ТОЛЬКО внутри записи
// конкретной модели — то есть у модели без профиля причины не было вовсе.
//
// ЧТО ДЕЛАЕТ ЭТА ФУНКЦИЯ. Отдаёт действующее значение потолка и честную причину
// НЕЗАВИСИМО от профилей: одна точка, которую API профилей кладёт рядом с
// картой effectiveContext. Профильная часть (что режет конкретную модель)
// остаётся в ProfileEffectiveWindow — вторая формула потолка в пакете запрещена
// (см. nctx_ceiling_r267.go).

// ClusterNCtxCeiling — действующий потолок авто-роста окна и его причина.
//
// envCeiling == 0 означает «потолок не задан»: тогда окно режется только
// физикой (VRAM/GGUF), которая проверяется на пути загрузки.
//
// limitedBy — стабильное имя источника ("env" или ""), на него смотрит WebUI;
// reason — текст для человека. Nil-safe: прокси может быть не инициализирован
// (диагностическое поле не должно ронять карточку).
func (p *Proxy) ClusterNCtxCeiling() (envCeiling int, limitedBy, reason string) {
	if p == nil {
		return 0, "", "балансер недоступен: потолок авто-роста окна неизвестен"
	}
	if p.nctxReload != nil {
		envCeiling = p.nctxReload.Config().AutoReloadMaxNCtx
	}
	if envCeiling > 0 {
		return envCeiling, "env",
			"потолок авто-роста окна LB_NCTX_RELOAD_MAX_N_CTX=" + strconv.Itoa(envCeiling) +
				"; заявленное в профиле модели окно может быть выше — тогда режет профиль, а не env"
	}
	return 0, "",
		"потолок авто-роста не задан (LB_NCTX_RELOAD_MAX_N_CTX пуст): окно не режется env-ом, " +
			"предел проверяется на загрузке (VRAM/GGUF)"
}
