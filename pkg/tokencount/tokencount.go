// Package tokencount — фолбэк-оценка числа токенов по тексту.
//
// # Зачем это существует
//
// Основной путь подсчёта токенов — реальный токенизатор модели
// (`llama_tokenize` через `c/bridge`, см. `Backend.CountTokens`). Но есть
// ситуации, когда токенизатор недоступен **by design**:
//
//   - модель ещё не загружена (холодный старт, cppworker только поднялся);
//   - модель выгружена idle-таймером;
//   - unit-тесты на stub-мосте (`-tags llama_stub`, llama.h не требуется);
//   - `llama_tokenize` вернул 0 для «сломанного» мультиязычного токенизатора.
//
// Во всех этих случаях раньше применялась эвристика `len(runes) / 4`
// («~4 символа на токен»). Она неверна для **любого** измеренного словаря,
// причём в опасную сторону — занижает счёт.
//
// # Измерения
//
// Числа ниже получены НЕ на глаз, а разбором реальных словарей из
// `c/llama.cpp/models/ggml-vocab-*.gguf`. Метод:
//
//	node scripts/vocab_stats.js      <vocab.gguf>   # статистика словаря по скриптам
//	node scripts/vocab_bpe_probe.js  <vocab.gguf>   # жадный BPE на образцах текста
//
// Второй скрипт воспроизводит разбор текста по словарю (на каждой позиции —
// самый длинный совпадающий токен) и считает реальное число токенов. Это
// консервативная оценка сверху: она недобирает длинные merge'и там, где
// llama.cpp выбрал бы более длинный токен, поэтому настоящий счёт может быть
// лишь НИЖЕ измеренного — то есть оценка не занижает.
//
// Образцы: латиница ~194 руны, кириллица ~182 руны, CJK ~48 рун.
// Результат (рун на токен; больше = плотнее упаковка):
//
//	словарь                   latin    cyrillic   cjk
//	gemma-4  (262k, gemma4)    2.43      2.12      1.33
//	command-r (256k)           2.43      1.00      1.00
//	phi-3    (32k,  phi3)      2.23      1.80      1.00
//	deepseek-llm (102k)        2.40      1.00      1.00
//	gpt-neox (50k)             2.31      1.00      1.00
//	qwen2    (152k)            2.49      1.00      1.00
//	llama-bpe (128k)           2.49      1.00      1.00
//	gpt-2    (50k)             2.23      1.00      1.00
//
// Для сравнения, эвристика `len(runes)/4` даёт ровно 4.0 руны на токен — то
// есть занижает латиницу на 63–81 %, а кириллицу в словарях без кириллических
// merge'ов — на 304 % (там каждый символ становится отдельным токеном).
//
// # Чем это важно
//
// Занижение счёта токенов — не косметика: результат идёт в `n_predict`
// (клампится под свободное место в контексте) и в preflight-проверку
// переполнения `n_ctx`. Если считать prompt «в 4 раза короче», чем он есть,
// запрос уходит за границу контекста и получает `prompt too long` вместо
// ответа. Поэтому константы выбраны по МИНИМУМУ измеренного (самый
// неблагоприятный словарь), а не по среднему, и округлены в безопасную
// сторону.
package tokencount

import "unicode/utf8"

// Скриптовые группы. Считаем только то, что реально влияет на плотность
// упаковки: сжимаемый текст против несжимаемого.
const (
	// runesPerTokenCompressible — для ASCII-букв и цифр. Измеренный максимум
	// плотности — 2.49 руны на токен (qwen2/llama-bpe), минимум 2.23 (phi-3,
	// gpt-2). Деление на 2 — оценка сверху на любом измеренном словаре.
	runesPerTokenCompressible = 2

	// runesPerTokenUncompressible — для пробелов, пунктуации и ВСЕГО
	// не-ASCII (кириллица, CJK, греческий, эмодзи).
	//
	// Почему 1, а не измеренные 2.12 у gemma-4: из восьми измеренных словарей
	// шесть не имеют кириллических merge'ов, и там текст токенизируется почти
	// по символу (qwen2: 1.27 руны/токен, CJK: 1.02). Ориентироваться на
	// лучший словарь значило бы занижать счёт на большинстве реальных моделей.
	//
	// Отдельно про пробелы и пунктуацию в ASCII: их тоже приходится считать
	// по символу. Это выглядит расточительно (пробел обычно 1 токен, но их
	// много не подряд), однако проверка на измеренных образцах показала, что
	// деление их на 2 (как букв) даёт ЗАНИЖЕНИЕ на смешанном тексте: в
	// qwen2-словаре кириллица идёт по символу, и общий счёт поднимается до
	// 1.78 руны/токен — то есть сжимаемость всего текста определяется
	// несжимаемой частью, а не латинской.
	runesPerTokenUncompressible = 1
)

// Estimate возвращает оценку числа токенов в тексте (не меньше 0).
//
// Оценка сознательно консервативна: она не занижает относительно реального
// токенизатора (см. измерения в doc-комментарии пакета). Для пустой строки
// возвращает 0.
//
// Вызывать только там, где реальный токенизатор недоступен. Если модель
// загружена — используйте Backend.CountTokens.
func Estimate(text string) int {
	if text == "" {
		return 0
	}

	compressible := 0
	uncompressible := 0

	for _, r := range text {
		if isCompressibleASCII(r) {
			compressible++
			continue
		}
		uncompressible++
	}

	// Деление с округлением ВВЕРХ: при compressible=3 (оценка 1.5) честнее
	// вернуть 2, чем 1 — снова в сторону «не занижать».
	compressibleTokens := (compressible + runesPerTokenCompressible - 1) / runesPerTokenCompressible
	return compressibleTokens + uncompressible*runesPerTokenUncompressible
}

// EstimateBytes — оценка по сырым байтам без декодирования в руны.
//
// Нужна на горячих путях, где текст уже лежит как []byte и нет смысла
// материализовать строку. Поведение совпадает с Estimate(string(b)) для
// валидного UTF-8: ASCII-буквы/цифры сжимаются вдвое, всё остальное
// (включая пробелы и пунктуацию) считается по символу. Невалидный UTF-8
// считается побайтово как несжимаемый — это завышает, что безопасно.
func EstimateBytes(b []byte) int {
	if len(b) == 0 {
		return 0
	}

	compressible := 0
	uncompressible := 0
	i := 0
	for i < len(b) {
		c := b[i]
		if c < utf8.RuneSelf {
			if isCompressibleASCII(rune(c)) {
				compressible++
			} else {
				uncompressible++
			}
			i++
			continue
		}
		_, size := utf8.DecodeRune(b[i:])
		if size <= 1 {
			// Невалидный UTF-8: байт как один несжимаемый символ.
			uncompressible++
			i++
			continue
		}
		uncompressible++
		i += size
	}

	compressibleTokens := (compressible + runesPerTokenCompressible - 1) / runesPerTokenCompressible
	return compressibleTokens + uncompressible*runesPerTokenUncompressible
}

// isCompressibleASCII — ASCII-буквы (A-Z, a-z) и цифры (0-9).
//
// Только они токенизируются плотнее одного символа на токен: связный
// латинский текст упаковывается в 2.2-2.5 руны на токен (см. измерения).
// Пробелы, пунктуация и весь не-ASCII сюда НЕ попадают — см. комментарий к
// runesPerTokenUncompressible.
func isCompressibleASCII(r rune) bool {
	switch {
	case r >= 'a' && r <= 'z':
		return true
	case r >= 'A' && r <= 'Z':
		return true
	case r >= '0' && r <= '9':
		return true
	default:
		return false
	}
}
