// reasoning_hold_r190.go — R190 (2026-10-20): удержание дельт из-за блока
// размышлений снимается, когда блок ЗАКРЫТ.
//
// ЖИВОЙ РАЗБОР (Cline, /api/chat с tools[], gemma-4 и Qwen3.8). Клиент не видел
// ничего до самого конца хода. В логе воркера:
//
//	"writeChatStreamResponseWithTools: reasoning отделён от ответа",
//	 reasoning_len=177, content_len=378
//
// Причина в предохранителе 1b: если вывод НАЧИНАЕТСЯ с маркера размышлений
// (`<think>`, `<channel>thought`, …), выставлялся `toolsHold = true` и больше
// НЕ снимался — все последующие дельты (уже видимый ответ!) уходили в буфер до
// конца генерации. На 27B-модели это минуты тишины: клиент считает, что
// соединение умерло, и рвёт ход.
//
// Правило: пока блок размышлений ОТКРЫТ — дельты держим (в content их отдавать
// нельзя, Cline показывал thinking как ответ). Как только блок ЗАКРЫТ — снимаем
// удержание и отдаём видимый ответ дельтами, начиная с позиции после закрывающего
// маркера. Если блок не закрыт вовсе — поведение прежнее (держим весь ход).
package main

import "strings"

// reasoningCloseMarkers — закрывающие маркеры каналов размышлений.
//
// Порядок не важен; ищем ПОСЛЕДНИЙ из встретившихся: у части моделей канал
// встречается несколько раз (чередование thought/answer).
var reasoningCloseMarkers = []string{
	"</think>",
	"</thinking>",
	"</reasoning>",
	"</analysis>",
	"<channel|>",
	"</|channel>",
}

// reasoningBlockEnd — позиция СРАЗУ ПОСЛЕ последнего закрывающего маркера.
//
// Возвращает -1, если закрывающего маркера нет (блок ещё открыт).
func reasoningBlockEnd(s string) int {
	best := -1
	for _, marker := range reasoningCloseMarkers {
		if idx := strings.LastIndex(s, marker); idx >= 0 {
			if end := idx + len(marker); end > best {
				best = end
			}
		}
	}
	return best
}
