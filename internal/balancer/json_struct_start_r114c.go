// content-дельте (балансер, Ollama-путь /api/chat).
//
// ЗАЧЕМ. Балансер умеет распознавать JSON-вызов инструмента, который модель
// выдала ТЕКСТОМ (некоторые модели так делают), и переупаковывать его в
// message.tool_calls. Накопление буфера начиналось только если content ЧАНКА
// НАЧИНАЛСЯ с триггера ('[', '<tool_call>', '{name' …). Живой дефект (Cline →
// балансер → cppworker, /api/chat): модель написала прозу и следом JSON вызова В
// ОДНОМ чанке (или JSON начался посреди чанка) — такой чанк уходил клиенту
// целиком, то есть в теле ответа оказывался обрывок вызова:
//
//	…I consider the task complete. [{"id":"call_submit_and_exit","type":
//	"function","function":{"name":"submit_and_exit","arguments":{"summary":…
//
// Ровно это оператор описал как «периодически возникают формы вызова
// инструментов» и «остаётся след [[ от применения инструмента».
//
// Правило: JSON-структура начинается там, где стоит '[' или '{', за которым сразу
// идёт '"', '{' или '['. Проза до этой позиции отдаётся клиенту, а с неё самой
// начинается накопление (дальше его разбирает detectAndExtractToolCallsFromContent).
package balancer

// jsonStructStartPos — позиция начала JSON-структуры в тексте.
//
// Требование к следующему символу ('"', '{' или '[') отсекает одиночные скобки в
// обычной прозе и в разметке markdown.
func jsonStructStartPos(s string) (int, bool) {
	for i := 0; i+1 < len(s); i++ {
		switch s[i] {
		case '{':
			if n := s[i+1]; n == '"' || n == '{' || n == '[' {
				return i, true
			}
		case '[':
			if n := s[i+1]; n == '{' || n == '[' || n == '"' {
				return i, true
			}
		}
	}
	// Одиночная скобка в самом конце: структура началась, следующий символ ещё не
	// пришёл — держим её, чтобы не выпустить начало вызова отдельным чанком.
	if n := len(s); n > 0 {
		if last := s[n-1]; last == '{' || last == '[' {
			return n - 1, true
		}
	}
	return 0, false
}
