// escaped_call_markup_r430.go — R430 (2026-11-04): вызов инструмента с
// ПЕРЕЭКРАНИРОВАННЫМИ ключами (`\"function\"`) опознаётся как разметка вызова, а
// не как обычный текст ответа.
//
// ЖИВОЙ ДЕФЕКТ (gemma-4-E4B-it + Cline через балансер, сборка R429, четыре
// прогона подряд). Модель выдала вызов в JSON-форме, но с экранированными
// кавычками у ключей и БЕЗ баланса скобок в конце:
//
//	…(The content generated in the previous turn is correct for this file).<channel|>[
//	[[{\"function\":{\"name\":\"editor\",\"arguments\":{\"path\":\"d:\\\\…\\index.html\",
//	\"new_text\":\"<!-- … </html>\"}]
//
// Следствия до фикса:
//   - ни один разбор (все девять стратегий) такой вызов не видит: они ищут
//     `"name"`/`"function"`, а тут `\"name\"`; к тому же объект не закрыт;
//   - `looksLikeToolCallMarkup` возвращал false, поэтому НЕ срабатывали ни
//     пояснение «вызов в нераспознанном формате», ни сохранение сырого вывода
//     (R427/R428) — дефект был невидим в диагностике;
//   - хвост считался обычной прозой и уезжал клиенту: `streamed_content_bytes`
//     3441 из `raw_len` 3442 — Cline сохранил 3,4 КБ мусора в истории.
//
// ПОЧЕМУ НЕ ПАРСИМ, А ТОЛЬКО ОПОЗНАЁМ. Разметка невалидна по построению:
// переэкранированы ТОЛЬКО структурные ключи, кавычки внутри `new_text` остались
// на своём уровне, а закрывающих скобок не хватает (`"}]` вместо `"}}]]`).
// «Починить» её значит угадать, что модель имела в виду, — цена ошибки: вызов
// инструмента с чужими/испорченными аргументами (запись файла не тем текстом).
// Поэтому такой вывод получает тот же контракт, что и прочая нераспознанная
// разметка (R428): в content разметка не попадает, сырой вывод сохраняется
// (R427), клиенту достаётся проза + пояснение «вызов не выполнен, повторите».
package main

import "strings"

// unparsedToolCallNoticeR430 — единственный текст пояснения для «вызов был, но
// распознать не смогли». Одно место: одинаковое сообщение на всех ветках, чтобы
// клиент и оператор видели одну формулировку (R428 ставил её в двух ветках
// копипастой).
const unparsedToolCallNoticeR430 = "Модель вызвала инструмент в нераспознанном формате — вызов не выполнен. Повторите запрос."

// escapedCallKeyMarkersR430 — ключи вызова в переэкранированном виде. Требуем
// минимум два: одиночный `\"name\"` встречается в обычном тексте про JSON
// (например, когда модель объясняет формат), пара — только в самой разметке.
var escapedCallKeyMarkersR430 = []string{
	`\"function\"`,
	`\"name\"`,
	`\"arguments\"`,
	`\"parameters\"`,
	`\"tool_calls\"`,
	`\"tool_call\"`,
}

// nonStreamVisibleContentR430 — видимый content для НЕпотоковых ответов, когда
// вызов не распознан.
//
// Зачем отдельная функция, а не правка в одном месте: «разметка вызова в теле
// ответа» — свойство не одного хендлера. На /api/chat (stream:false) и на
// OpenAI-поверхности видимый текст собирался как
// `stripToolCallMarkup(cleanFinalContent(…))`, а эта чистка знает только
// ТЕГОВЫЕ обёртки и завершённые JSON-объекты: переэкранированную разметку
// (`\"name\"`), питоновскую форму `call:NAME(` и хвост без баланса скобок она не
// снимает — они уезжают клиенту (проверено живьём: echo-проба вернула в content
// `[[{\"function\":{\"name\":\"editor\"…`).
//
// Возвращает content и признак «разметка была, вызов не распознан» — по нему
// вызывающий сохраняет сырой вывод в диагностику (R427).
func nonStreamVisibleContentR430(parsed string) (string, bool) {
	if !looksLikeToolCallMarkup(parsed) {
		return stripToolCallMarkup(cleanFinalContent(parsed)), false
	}
	return visibleContentBeforeMarkupR430(parsed), true
}

// visibleContentBeforeMarkupR430 — видимый текст, когда разметка вызова ЕСТЬ, но
// не распознана: проза до её начала + пояснение «вызов не выполнен».
//
// Нужна и потоковому пути: там финальный content (и единственная дельта короткого
// ответа R424) собирался как stripToolCallMarkup(cleanFinalContent(…)) — и
// переэкранированная разметка доезжала до клиента именно этим каналом (живая
// проба после первой правки R430: дельта содержала `[[{\"function\"…`, хотя
// потоковая нарезка буфера её уже не отдавала).
func visibleContentBeforeMarkupR430(parsed string) string {
	visible, _ := visibleTailR429(parsed, 0)
	visible = strings.TrimSpace(visible)
	if visible == "" {
		return unparsedToolCallNoticeR430
	}
	return visible + "\n\n" + unparsedToolCallNoticeR430
}

// escapedCallKeyCountR430 — сколько РАЗНЫХ переэкранированных ключей вызова в s.
func escapedCallKeyCountR430(s string) int {
	n := 0
	for _, m := range escapedCallKeyMarkersR430 {
		if strings.Contains(s, m) {
			n++
		}
	}
	return n
}

// looksLikeEscapedToolCallR430 — в выводе переэкранированная разметка вызова.
func looksLikeEscapedToolCallR430(s string) bool {
	return escapedCallKeyCountR430(s) >= 2
}

// escapedCallMarkupStartR430 — позиция начала переэкранированной разметки вызова
// (-1, если её нет).
//
// Началом считаем ОБЁРТКУ вызова, а не первый ключ: клиенту нельзя отдавать и
// `[[{` перед `\"function\"` — это обрывок разметки. Границу ищем так: от первого
// переэкранированного ключа идём назад, пока идут только скобки и пробельные
// (буква прозы останавливает скан — через слова не перешагиваем), затем
// сдвигаемся вперёд до ближайшей '{'/'['. Если обёртки нет — режем по ключу.
func escapedCallMarkupStartR430(s string) int {
	best := -1
	for _, m := range escapedCallKeyMarkersR430 {
		p := strings.Index(s, m)
		if p < 0 {
			continue
		}
		if best < 0 || p < best {
			best = p
		}
	}
	if best < 0 {
		return -1
	}
	lo := best
	for i := best - 1; i >= 0; i-- {
		switch s[i] {
		case '[', '{', '}', ']', ' ', '\t', '\r', '\n':
			lo = i
			continue
		}
		break
	}
	// От границы прогона идём вперёд до первой открывающей скобки: закрывающие
	// скобки из прозы (`… ]`) не должны попасть в начало разметки.
	for i := lo; i < best; i++ {
		if s[i] == '[' || s[i] == '{' {
			return i
		}
	}
	return best
}
