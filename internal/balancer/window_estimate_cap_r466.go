// window_estimate_cap_r466.go — R466 (2026-11-06): оценка промпта не может
// служить причиной отказа «окно физически не поместится».
//
// ЖИВОЙ ДЕФЕКТ (второй стенд: A10 ×2, 50 ГБ, Qwen3.8-27B, Cline). Клиент
// показывал занятый контекст 63.6k, а балансер отвечал, что «требуется 151743
// токенов на контекстное окно», и НЕ поднимал окно. Причина: нужное окно
// выводится из ОЦЕНКИ промпта (эвристика по символам, без токенизатора), а
// эвристика на обычном тексте завышает в ~2.4 раза. Дальше это же выведенное
// число сравнивалось с физическим потолком модели — и запрос получал 413
// «окно физически не поместится».
//
// Клиент при этом не просил ничего лишнего: ни num_ctx, ни сверхбольшой
// max_output_tokens. То есть отказ был построен на нашей же догадке.
//
// ПРАВИЛО (две части):
//  1. Отказ 413 по физике остаётся ТОЛЬКО для окна, которое ЯВНО запросил
//     клиент (num_ctx). Догадка балансера отказом быть не может.
//  2. Выведенное из оценки окно урезается до потолка (с учётом слотов):
//     перезагрузка до потолка полезна — реальный промпт может влезть, — а отказ
//     по завышенной оценке ломает ход клиента.
package balancer

// derivedWindowCapR466 — потолок окна НА КЛИЕНТА при заданном суммарном
// потолке и числе слотов (llama.cpp делит суммарное окно между слотами).
//
// Выравнивание ВНИЗ до 256 обязательно: обратный пересчёт
// (perClientToTotal → PadContext(окно)×слоты) округляет окно ВВЕРХ, и «потолок
// на клиента» = ceiling/slots при неделимом потолке дал бы суммарное окно
// БОЛЬШЕ потолка — то есть тот же 413, от которого мы уходим.
func derivedWindowCapR466(ceiling, slots int) int {
	if ceiling <= 0 {
		return 0
	}
	if slots <= 1 {
		return ceiling
	}
	const align = 256
	per := ceiling / slots / align * align
	if per <= 0 {
		return 0
	}
	return per
}

// capDerivedWindowR466 — урезать выведенное (не клиентское) окно до потолка.
// Возвращает (значение, было_ли_урезано).
func capDerivedWindowR466(derived, ceiling, slots int) (int, bool) {
	cap := derivedWindowCapR466(ceiling, slots)
	if derived <= 0 || cap <= 0 || derived <= cap {
		return derived, false
	}
	return cap, true
}
