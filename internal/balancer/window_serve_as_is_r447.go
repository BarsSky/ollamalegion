// не мешает, окно растят как раньше. Это правило отвечает на другой вопрос —
// «можно ли отказать/отложить СЕЙЧАС», — и отвечает на него один раз для всех
// путей: guard R299 (вход preflight), blocker R288 (перед admission-очередью),
// вердикт R301 (не-стриминговая ветка: там отказывали каждому «нужен рост» при
// чужом стриме) и единое решение R493 (ветка занятости).
//
// estimated <= 0 означает «оценки промпта нет»: сравнивать нечего, отказывать по
// догадке нельзя — так же поступают R301 («отказываем только когда в окно не
// влезает САМ ПРОМПТ») и PromptFits в decideWindowR493.
package balancer

import "fmt"

// windowServeAsIsR447 — обслужит ли загруженное окно запрос как есть.
//
// Таблица (первые два пункта совпадают с growthNeedR447 — правило роста и
// правило отказа не могут расходиться на «промпт не влезает» и «клиент попросил
// больше»):
//
//	loaded <= 0        → true  (окно неизвестно: по догадке не отказываем)
//	requested > loaded → false (воркер отвергнет чужой num_ctx)
//	estimated > loaded → false (воркер ответит кадром ошибки: промпт не влезает)
//	иначе              → true  (обслуживаем; бюджет ответа урежет воркер)
func windowServeAsIsR447(estimated, loaded, requested int) (bool, string) {
	if loaded <= 0 {
		return true, "загруженное окно неизвестно — отказывать по догадке нельзя"
	}
	if requested > loaded {
		return false, fmt.Sprintf(
			"клиент попросил окно %d больше загруженного %d — воркер отвергнет чужой num_ctx",
			requested, loaded)
	}
	if estimated > 0 && estimated > loaded {
		return false, fmt.Sprintf("промпт (%d) не влезает в окно слота (%d)", estimated, loaded)
	}
	return true, fmt.Sprintf(
		"загруженное окно (%d) обслуживает промпт (%d) как есть: бюджет ответа воркер урежет сам",
		loaded, estimated)
}
