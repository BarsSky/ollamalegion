// СКЛЕИВАЮТСЯ, а не копятся в канале подписчика.
//
// ЖИВАЯ ЖАЛОБА (лог балансера): `failed to send websocket snapshot` — и в
// браузере «нет связи» с последующим переподключением. Причина не в снапшоте,
// а в их количестве: канал подписчика (`MetricsBroker.Subscribe`) имеет буфер
// **100**, публикация неблокирующая (при заполнении считает дропы). Когда
// клиент не читает (свёрнутая/спящая вкладка, медленная сеть), в канале
// накапливается до 100 СТАРЫХ снапшотов. Обработчик WS вычитывает их по одному
// и на каждый ставит write deadline 30 с: одна застрявшая запись убивала
// соединение, а остальные 99 снапшотов были уже не нужны — они устарели.
//
// ЧТО ЗДЕСЬ. Перед отправкой состояния дренаж канала: берём ПОСЛЕДНИЙ снапшот,
// все промежуточные отбрасываем (считаем, чтобы это было видно в логе). Так
// стоимость тика не зависит от того, насколько отстал клиент: одна запись — одно
// свежее состояние. Клиент, который не читает ВООБЩЕ, по-прежнему отвалится по
// write deadline (это не лечится склейкой: сокет мёртв), но «медленный» клиент
// больше не получает 30-секундную блокировку на устаревших данных.
package api

// drainLatestClusterSnapshot — оставить самый свежий снапшот из канала.
//
// first — уже прочитанный снапшот (его вызывает select в обработчике). Возвращает
// самый новый из накопившихся, число отброшенных устаревших и признак закрытого
// канала (подписка снята — вызывающий обязан выйти из цикла).
//
// Канал только вычитывается и никогда не блокирует: используется non-blocking
// default, поэтому вызов безопасен в горячем select-цикле.
func drainLatestClusterSnapshot(ch <-chan []byte, first []byte) (latest []byte, skipped int, closed bool) {
	latest = first
	for {
		select {
		case next, ok := <-ch:
			if !ok {
				return latest, skipped, true
			}
			latest = next
			skipped++
		default:
			return latest, skipped, false
		}
	}
}
