// ВСЕХ ПУТЕЙ (этап 3 плана `refactoring-plan.ru.md`, флаг LB_WINDOW_UNIFIED).
//
// ЖИВОЙ ДЕФЕКТ, ради которого это существует (план §1, таблица «окно решается
// четырьмя механизмами с разными правилами»): один и тот же JSON обслуживается
// на `/api/chat` и на `/v1/chat/completions` РАЗНЫМИ машинами. Короткий промпт
// на `/api/chat` обслуживается загруженным окном (R447), а на `/v1` тот же
// запрос получает 503 — потому что правило «окна мало ≠ окно надо растить»
// (R447) и правило «завышенная оценка не отменяет рост» (R466) были вписаны в
// ОДИН из путей, а второй считал по-своему.
//
// ЧТО ЗДЕСЬ. Одна чистая функция `decideWindowR493`: на входе ЧИСЛА и ФАКТЫ
// (сколько нужно, сколько загружено, сколько просил клиент, слоты, потолок,
// занятость, почему этот путь не может расти), на выходе один вердикт с видом,
// целью, сроком повтора и причиной. Внутри — правила, которые до сих пор были
// размазаны по четырём местам:
//
//	R447 — «окна мало» не значит «окно надо растить» (промпт влезает → обслужить);
//	R466 — завышенная НАША оценка (клиент окна не просил) урезается до потолка,
//	       а не отменяет рост;
//	R288 — занятость (чужие стримы, идущая перезагрузка) означает «ждать», а не
//	       «перезагрузить поверх живого ответа»;
//	R385 — цель роста: выравнивание по 256 и ступень 8k, но никогда ниже
//	       загруженного окна (R493-12h);
//	R304 — донор своих копий не держит, растить ему нечего.
//
// ПОЧЕМУ ЧИСТАЯ ФУНКЦИЯ, А НЕ МЕТОД Proxy. Решение о окне должно быть проверяемо
// таблицей «вход → вердикт» без кластера, метрик и HTTP. Пока оно читало
// состояние по месту, любая проверка была сценарием, а расхождение путей
// ловилось только на стенде. Прокси-обёртка
// (`Proxy.windowInputForR493`/`windowDecisionForR493`) только СОБИРАЕТ входные
// числа — не решает.
//
// ЧЕМ ОТЛИЧАЕТСЯ ПУТЬ. Его отличие — это ВХОД, а не правило: путь, который не
// умеет перезагружать модель под запрос (стриминг с выключенным ростом, донор),
// передаёт `GrowBlockedBy`. Тогда один и тот же набор чисел даёт один и тот же
// вид вердикта на любом пути, а «кто именно нажмёт кнопку перезагрузки» остаётся
// делом вызывающего — это транспорт, а не решение.
package balancer

import (
	"fmt"

	"ollama-loadbalancer/internal/cppbackend"
)

// windowKindR493 — вид вердикта. Строка, а не iota: вид попадает в лог и в
// сравнение путей, и «2» в логе не читается.
type windowKindR493 string

const (
	// windowNoopR493 — окно известно и его хватает (или неизвестно: числами не
	// спекулируем). Решение не наше, запрос идёт дальше как есть.
	windowNoopR493 windowKindR493 = "noop"
	// windowServeR493 — окно растить НЕ нужно: промпт с местом под ответ влезает.
	// Запрошенное клиентом большее окно приводит к загруженному (R83).
	windowServeR493 windowKindR493 = "serve"
	// windowDeferR493 — рост нужен, но сейчас мешает занятость. Отказ «ждите» с
	// числами и сроком повтора (R288/R299).
	windowDeferR493 windowKindR493 = "defer"
	// windowGrowR493 — рост нужен и возможен: Target — окно НА КЛИЕНТА, до
	// которого надо поднять модель. Перезагружает вызывающий.
	windowGrowR493 windowKindR493 = "grow"
	// windowRefuseR493 — рост нужен, но невозможен по причине, не связанной с
	// занятостью (потолок, выключатель, донор). Why — настоящая причина: на
	// стриминге клиент увидит именно её (R472), а не «стриминг не растит окно».
	windowRefuseR493 windowKindR493 = "refuse"
)

// windowInputR493 — всё, что нужно для решения. Ни одного поля «по месту».
type windowInputR493 struct {
	// GrowBlockedBy — почему ЭТОТ путь не может растить окно ("" = может).
	// Так отличие пути становится входом, а не вторым набором правил:
	// стриминг с LB_NCTX_GROW_FOR_STREAM=0 передаёт причину выключателя,
	// донор — причину донора, не-стриминговый путь (preflight умеет reload)
	// оставляет пусто.
	GrowBlockedBy string
	Needed        int // сколько нужно: max(оценка промпта + бюджет вывода, запрошенное окно)
	Estimated     int // оценка ТОЛЬКО промпта (без бюджета вывода)
	Requested     int // окно, которое клиент запросил явно (0 = не просил)
	Loaded        int // окно ОДНОГО слота сейчас (0 = неизвестно)
	Slots         int // число слотов модели (для потолка R466; 0/1 = один)
	Ceiling       int // потолок окна НА КЛИЕНТА (0 = неизвестен)
	Active        int // сколько стримов идёт сейчас на этом бэкенде/модели
	// ReloadPending — перезагрузка этой модели уже идёт.
	ReloadPending bool
}

// windowDecisionR493 — вердикт. Числа заполняются всегда: лог и тело отказа
// обязаны называть то же состояние мира, по которому принято решение.
type windowDecisionR493 struct {
	Kind          windowKindR493
	Why           string
	Needed        int
	Estimated     int
	Loaded        int
	Requested     int // окно, которое клиент запросил явно (0 = не просил)
	Target        int // окно НА КЛИЕНТА для перезагрузки (Kind=grow)
	RetryAfterSec int
	Active        int // стримов шло на момент решения (число для тела отказа)
	// PromptFits — промпт (без бюджета вывода) влезает в загруженное окно.
	// Нужен вызывающему: когда рост невозможен, запрос всё равно обслуживается,
	// если влезает сам промпт (бюджет генерации воркер урезает сам).
	PromptFits bool
	// Capped — R466 сработал: выведенное окно урезано до потолка.
	Capped bool
	// ReloadPending — перезагрузка этой модели шла на момент решения.
	ReloadPending bool
}

// RetryAfter — срок повтора, который ОБЯЗАН попасть и в текст причины, и в тело
// (R447: «retry in 60 seconds» рядом с `retryAfterSec: 30` — это дефект).
func (d windowDecisionR493) RetryAfter() int { return d.RetryAfterSec }

// decideWindowR493 — ЕДИНСТВЕННОЕ место, где решается «растим / обслуживаем
// загруженным / ждём / расти нельзя».
func decideWindowR493(in windowInputR493) windowDecisionR493 {
	d := windowDecisionR493{
		Needed: in.Needed, Estimated: in.Estimated, Loaded: in.Loaded,
		Requested: in.Requested, Active: in.Active, ReloadPending: in.ReloadPending,
	}
	// Загруженное окно неизвестно (модель не загружена, метрик нет) или
	// потребность неизвестна — сравнивать нечего, решение принимает прежний путь.
	if in.Loaded <= 0 || in.Needed <= 0 {
		d.Kind = windowNoopR493
		d.Why = "загруженное окно или потребность неизвестны"
		return d
	}

	// R466 (2026-11-06): завышенная НАША оценка не отменяет рост.
	//
	// needed = оценка промпта + бюджет вывода, оценка — по символам (без
	// токенизатора), на живых стендах завышает в 2–3 раза. Если окно выведено
	// нами (клиент num_ctx не присылал), урезаем его до потолка и пробуем рост.
	// Явно запрошенное клиентом окно сверх потолка — это его требование, а не
	// наша догадка: остаётся как есть и честно отказывается ниже.
	if in.Requested <= 0 && in.Needed > in.Loaded {
		if capped, cut := capDerivedWindowR466(in.Needed, in.Ceiling, in.Slots); cut && capped > in.Loaded {
			in.Needed = capped
			d.Needed = capped
			d.Capped = true
		}
	}
	if in.Needed <= in.Loaded {
		d.Kind = windowNoopR493
		d.Why = fmt.Sprintf("окно достаточно: нужно %d, загружено %d", in.Needed, in.Loaded)
		return d
	}

	// Граница отказа: промпт (без бюджета вывода) влезает в загруженное окно.
	// Считается всегда — вызывающему это нужно, если рост окажется невозможен.
	d.PromptFits = in.Estimated <= 0 || in.Estimated <= in.Loaded

	// R447 (2026-11-06): «окна мало» ≠ «окно надо растить».
	//
	// Бюджет вывода — не требование модели (воркер урезает num_predict по
	// свободному месту сам), поэтому короткий запрос без явно запрошенного окна
	// обслуживается загруженным окном: ни роста (перезагрузка = минуты простоя и
	// обрыв чужого процесса), ни отказа (503 на вопрос в три токена).
	// Растим только по требованию самого запроса: промпт не влезает ИЛИ клиент
	// явно попросил окно больше загруженного.
	if need, why := growthNeedR447(in.Estimated, in.Loaded, in.Requested); !need {
		// Делать нечего: клиент больше загруженного окна не просил, промпт с
		// запасом под ответ влезает. Подменять num_ctx не нужно — он и так не
		// больше загруженного.
		d.Kind = windowNoopR493
		d.Why = why
		return d
	}

	// R288 (2026-11-06): занятость означает «ждать», а не «перезагрузить поверх
	// живого ответа». Перезагрузка рвёт чужой стрим (R271), поэтому пока идёт
	// стрим или уже начата перезагрузка — отказ с числами и сроком повтора.
	if in.Active > 0 || in.ReloadPending {
		d.Kind = windowDeferR493
		d.RetryAfterSec = growthDeferRetryAfterSecR447
		d.Why = fmt.Sprintf("рост нужен, но мешает занятость: активных стримов %d, перезагрузка идёт %t",
			in.Active, in.ReloadPending)
		return d
	}

	// Путь, который не умеет растить окно, говорит это ПРИЧИНОЙ, а не молчанием:
	// иначе клиент видит «стриминг не растит окно» вместо настоящей причины
	// (R472 — живой дефект, когда так прятался выключатель роста).
	if in.GrowBlockedBy != "" {
		d.Kind = windowRefuseR493
		d.Why = in.GrowBlockedBy
		return d
	}

	// Потолок: если запросу нужно БОЛЬШЕ физического/операторского предела, рост
	// бессмыслен — перезагрузка на потолок запрос всё равно не обслужит, а стоит
	// выгрузки 27B. Проверяется по «нужному», а не по урезанной цели.
	if in.Ceiling > 0 && in.Needed > in.Ceiling {
		d.Kind = windowRefuseR493
		d.Why = fmt.Sprintf("нужно %d, потолок авто-роста %d", in.Needed, in.Ceiling)
		return d
	}

	target, grow := growthTargetR493(in.Needed, in.Loaded, in.Ceiling)
	if !grow {
		// Цель роста не больше загруженного окна: перезагружать нечего, а «вниз»
		// окно не опускается никогда (R493-12h). Если клиент просил больше
		// загруженного — обслуживаем с подменой num_ctx, иначе делать нечего.
		d.Kind = windowNoopR493
		d.Requested = in.Requested
		if in.Requested > in.Loaded {
			d.Kind = windowServeR493
		}
		d.Why = fmt.Sprintf("окно уже покрывает запрос: нужно %d, выровненное %d, загружено %d",
			in.Needed, cppbackend.PadContext(in.Needed), in.Loaded)
		return d
	}
	d.Kind = windowGrowR493
	d.Target = target
	d.RetryAfterSec = streamGrowthRetryAfterSecR385
	d.Why = fmt.Sprintf("рост возможен: нужно %d, загружено %d, цель %d", in.Needed, in.Loaded, target)
	return d
}
