// growth_request_need.go — R447 (2026-11-06): «окну мало» и «окно нужно
// растить» — два разных вопроса, и до этой правки второй решался без первого.
//
// ЖИВОЙ ДЕФЕКТ (и он же причина красного CI). Запрос «Привет!» на модель,
// загруженную с окном 2048, получал отказ и ЗАПУСКАЛ перезагрузку модели, хотя
// промпту нужно 3 токена:
//
//	model "test-model" needs 4099 tokens of context; the loaded window is 2048 —
//	the balancer has started reloading the model to the requested window, retry in 60s
//
// Откуда 4099: `neededWindowTokensR330` = оценка промпта + БЮДЖЕТ ВЫВОДА (4096).
// Бюджет вывода входит в «сколько нужно окну», но НЕ означает, что модель не
// может ответить: воркер урезает num_predict по свободному месту сам. Рост нужен
// только когда места под ответ реально не остаётся (см. ниже), а не всегда,
// когда `needed` больше окна.
//
// Последствия прежнего правила:
//
//   - балансер рвал работающий процесс перезагрузкой модели (unload+load) на
//     каждый короткий запрос — то самое «медленно и отваливается» на стенде;
//   - стриминговый путь (R301) отказывал в обслуживании промпта, который воркер
//     обслужил бы укороченным ответом;
//   - исход зависел от свободной VRAM (рост разрешён, только пока физика это
//     позволяет), поэтому один и тот же вход давал то 200 (0.01 c), то 503 +
//     перезагрузку (0.5 c) — флак `TestChatStreaming` в CI.

package balancer

import "fmt"

// growthNeedR447 — нужен ли запросу рост окна.
//
// Растим окно только тогда, когда этого требует САМ ЗАПРОС:
//
//  1. промпт не влезает в окно одного слота — иначе воркер ответит кадром
//     ошибки внутри 200 (живой дефект R301);
//  2. клиент ЯВНО попросил окно больше загруженного (R385: «просил 16384 при
//     загруженных 8192» — законное требование, а не догадка балансера);
//  3. после префилла не остаётся места под осмысленный ответ, то есть
//     `loaded - estimated < agentOutputReserveMinTokens` (256). Это нижняя
//     граница «ход агента вообще имеет смысл» из R253: сюда попадает окно
//     2048 при промпте 2000, и туда НЕ попадает окно 2048 при промпте в
//     3 токена (свободно ≈2045).
//
// Полный бюджет вывода (`agentOutputBudget`, 4096 по умолчанию) в условие
// намеренно НЕ входит: это верхняя граница запроса, а не требование модели —
// именно её сравнение с окном и давало 503 на короткий вопрос.
//
// estimated <= 0 означает «оценки промпта нет»: сравнивать нечего, полагаемся
// только на явно запрошенное окно.
//
// R664 (2026-11-20): функция отвечает только на вопрос «нужен ли НЕМЕДЛЕННЫЙ
// рост» (иначе запрос не обслужить). Полное решение — growthActionForR664:
// обслужить как есть / вырасти в фоне / вырасти немедленно / отказать с числами.
//
// ШАГ B: «нужен рост» и «рост разрешён» — разные вопросы. Когда данные не
// влезают, а окно клиент НЕ заявил, growthActionForR664 отвечает
// growthRefuseR664: росту нет основания (R83/R68), поэтому need=false. Решение
// вызывающего — отказ с числами, а не «обслужить как есть»: промпт в окно не
// влезает (R447 разрешает обслужить только влезающий).
func growthNeedR447(estimated, loaded, requested int) (need bool, why string) {
	action, why := growthActionForR664(estimated, loaded, requested)
	return action == growthRequiredR664, why
}

// growthActionR664 — что делать с окном по этому запросу.
type growthActionR664 int

const (
	// growthNoneR664 — обслужить загруженным окном, окно не трогать.
	growthNoneR664 growthActionR664 = iota
	// growthBackgroundR664 — обслужить сейчас, окно поднять в фоне: клиент заявил
	// больше загруженного, но текущие данные влезают (R664: проактивная просьба
	// агента не должна держать его запрос минуты).
	growthBackgroundR664
	// growthRequiredR664 — обслужить нельзя: данные не влезают и клиент заявил
	// покрывающее окно. Рост немедленный, запрос ждёт/повторяет.
	growthRequiredR664
	// growthRefuseR664 — обслужить нельзя, но роста клиент не просил: отказ с
	// числами (413 context_window_exhausted_no_growth_request), модель НЕ
	// перезагружаем. Включён шагом B (2026-11-20).
	growthRefuseR664
)

// String — человекочитаемое имя действия (для логов: оператор не должен
// расшифровывать числа).
func (a growthActionR664) String() string {
	switch a {
	case growthBackgroundR664:
		return "grow_in_background"
	case growthRequiredR664:
		return "grow_now"
	case growthRefuseR664:
		return "refuse_with_numbers"
	default:
		return "none"
	}
}

// growthActionForR664 — ОДНО правило «что делать с окном» (R664, шаг A).
//
// ЖИВОЙ РАЗБОР (двухузловой стенд, 2026-11-20). Клиент «сжал» контекст и заявил
// окно меньше загруженного — балансер обслуживал как есть (и это правильно). А
// когда клиент заявлял окно больше загруженного при промпте в 15 токенов,
// балансер перезагружал модель (59.7 с на 4B, минуты на 27B) и держал запрос всё
// это время — хотя данные влезали в текущее окно с запасом.
//
// ШАГ A (этот). Триггер роста прежний — ЗАЯВКА КЛИЕНТА (как и в старом
// контракте). Меняется только ЦЕНА: если данные влезают в текущее окно, запрос
// обслуживается СРАЗУ, а окно поднимается в фоне до заявленного значения.
//
// ШАГ B (2026-11-20, включён здесь). Второй случай — данные НЕ влезают, а окно
// клиент НЕ заявил. Раньше балансер выводил окно из СВОЕЙ оценки промпта, то есть
// растил вслепую под число, которого никто не просил (оценка по символам завышает
// в 2–3 раза — R466), и платил за это перезагрузкой на десятки секунд…минуты.
// Теперь основание роста одно — заявка клиента (R83/R68), и без неё ответ честный:
// отказ с числами «сколько в промпте, сколько загружено, сколько нужно заявить»
// (growthRefuseR664). Модель при этом НЕ перезагружается, окно не уменьшается
// (R294).
//
// ПРАВИЛО:
//
//	данные влезают с местом под ответ, заявки больше загруженного нет → ничего
//	данные влезают, клиент заявил больше загруженного                    → ФОН
//	данные влезают, но под ответ меньше минимума                        → рост (как было)
//	данные не влезают, клиент заявил покрывающее окно                   → рост немедленный
//	данные не влезают, клиента окно не заявлено                         → ОТКАЗ с числами
//
// «Под ответ меньше минимума» (R447 п.3) остаётся ПРИЧИНОЙ РАСТИ, а не отказа:
// промпт в окно влезает, воркер обслуживает такой запрос укороченным ответом, и
// отказ отнял бы у клиента работающий ход (window_serve_as_is.go).
//
// Цель роста — РОВНО заявленное клиентом окно (для фоновой ветки), а не оценка
// промпта и не профиль: иначе окно уползало бы к числу, которого клиент не просил.
func growthActionForR664(estimated, loaded, requested int) (growthActionR664, string) {
	if loaded <= 0 {
		return growthNoneR664, "загруженное окно неизвестно"
	}
	dataFits := estimated <= 0 || estimated <= loaded
	if dataFits {
		if requested > loaded {
			return growthBackgroundR664, fmt.Sprintf(
				"клиент заявил окно %d больше загруженного %d, данные (%d) влезают — рост в фоне",
				requested, loaded, estimated)
		}
		if estimated > 0 {
			if room := loaded - estimated; room < agentOutputReserveMinTokens {
				return growthRequiredR664, fmt.Sprintf(
					"под ответ остаётся %d токенов (промпт %d, окно %d), меньше минимума %d",
					room, estimated, loaded, agentOutputReserveMinTokens)
			}
		}
		return growthNoneR664, fmt.Sprintf(
			"данные (%d) влезают в окно слота (%d) с местом под ответ, клиент больше не просил", estimated, loaded)
	}
	// ШАГ B: данные не влезают. Рост разрешён только по ЗАЯВКЕ клиента — иначе
	// ответ «откажи с числами», а не «перезагрузи модель под нашу оценку».
	if requested > loaded {
		return growthRequiredR664, fmt.Sprintf(
			"промпт (%d) не влезает в окно слота (%d), клиент заявил окно %d — рост по заявке",
			estimated, loaded, requested)
	}
	return growthRefuseR664, fmt.Sprintf(
		"промпт (%d) не влезает в окно слота (%d), окно клиент не заявил — отказ с числами, модель не перезагружаем",
		estimated, loaded)
}
