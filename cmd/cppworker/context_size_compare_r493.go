package main

import "ollama-loadbalancer/internal/cppbackend"

// sameContextSizeR493 — совпадает ли запрошенное окно с загруженным С УЧЁТОМ
// выравнивания загрузчика.
//
// Граничные случаи:
//   - requested <= 0: «окно не задано» — сравниваем напрямую (прежнее поведение,
//     иначе старые вызовы без contextSize начали бы считаться совпадением);
//   - loaded <= 0: модели ещё нет — разница есть (нужна загрузка);
//   - равенство после выравнивания: разницы нет.
func sameContextSizeR493(loaded, requested int) bool {
	if requested <= 0 || loaded <= 0 {
		return loaded == requested
	}
	if loaded == requested {
		return true
	}
	return cppbackend.PadContext(requested) == loaded
}
